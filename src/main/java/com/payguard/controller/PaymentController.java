package com.payguard.controller;

import com.payguard.dto.PaymentRequest;
import com.payguard.dto.TransactionResponse;
import com.payguard.service.PaymentResult;
import com.payguard.service.PaymentService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/api/payments")
public class PaymentController {

    private final PaymentService paymentService;

    public PaymentController(PaymentService paymentService) {
        this.paymentService = paymentService;
    }

    @Operation(summary = "Send money between accounts",
            description = "Safe to retry: repeating a request with the same Idempotency-Key never charges twice.")
    @PostMapping
    public ResponseEntity<TransactionResponse> pay(
            @Parameter(description = "Unique per payment, e.g. a UUID generated by the client")
            @RequestHeader("Idempotency-Key") @NotBlank @Size(max = 100) String idempotencyKey,
            @Valid @RequestBody PaymentRequest request) {

        PaymentResult result = paymentService.pay(idempotencyKey, request);
        return ResponseEntity
                .status(result.replayed() ? HttpStatus.OK : HttpStatus.CREATED)
                .header("Idempotent-Replayed", String.valueOf(result.replayed()))
                .body(result.transaction());
    }
}
